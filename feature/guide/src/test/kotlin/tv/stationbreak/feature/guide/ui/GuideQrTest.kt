package tv.stationbreak.feature.guide.ui

import com.google.zxing.BarcodeFormat
import com.google.zxing.BinaryBitmap
import com.google.zxing.DecodeHintType
import com.google.zxing.EncodeHintType
import com.google.zxing.RGBLuminanceSource
import com.google.zxing.common.HybridBinarizer
import com.google.zxing.qrcode.QRCodeReader
import com.google.zxing.qrcode.QRCodeWriter
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * The user-guide QR code (#1105): a static vector drawable, committed, never made at runtime (no QR library ships).
 * This file is also its generator, so it is reproducible: to write the drawable again after the URL changes, run
 *
 *     GUIDE_QR_WRITE=1 ./gradlew :feature:guide:testDebugUnitTest --tests '*GuideQrTest' --rerun
 *
 * The tests decode the committed file and compare it to the URL the app's own strings say, so a changed URL cannot
 * ship with the old code. ZXing is a test-only dependency.
 */
class GuideQrTest {
    private val drawable = File("src/main/res/drawable/guide_user_guide_qr.xml")

    // The one string the viewer reads and types: no scheme, no trailing slash. The code encodes https:// and the slash.
    private val shownUrl: String by lazy {
        val entry = Regex("""<string name="guide_help_url_text">([^<]*)</string>""")
        entry.find(File("src/main/res/values/strings.xml").readText())!!.groupValues[1]
    }
    private val url get() = "https://$shownUrl/"

    @Test
    fun theCommittedDrawableIsWhatTheGeneratorWritesForTheUrl() {
        if (System.getenv("GUIDE_QR_WRITE") == "1") drawable.writeText(render(url))
        assertEquals(render(url), drawable.readText())
    }

    @Test
    fun theCodeDecodesToTheExactUrl_withNoQueryAndNothingElse() {
        val decoded = decode(drawable.readText())
        assertEquals("https://stationbreak.tv/guide/", decoded)
        assertEquals(url, decoded)
        assertFalse(decoded.contains('?'))
        assertFalse(decoded.contains('#'))
    }

    @Test
    fun theCodeIsInkOnCream_withAFourModuleQuietZone_inEveryTheme() {
        val text = drawable.readText()
        val view = Regex("""viewportWidth="(\d+)"""").find(text)!!.groupValues[1].toInt()
        val modules = QRCodeWriter().encode(url, BarcodeFormat.QR_CODE, 0, 0, HINTS).width
        assertEquals(modules + 2 * QUIET, view)
        val fills = Regex("""fillColor="(#[0-9A-F]+)"""").findAll(text).map { it.groupValues[1] }.toList()
        assertEquals(listOf(CREAM, INK), fills)
        // Every dark run lies inside the quiet zone's border.
        for ((x, y, n) in dark(text)) {
            assertTrue(x >= QUIET && y >= QUIET && x + n <= view - QUIET && y < view - QUIET)
        }
    }

    private fun render(url: String): String {
        val matrix = QRCodeWriter().encode(url, BarcodeFormat.QR_CODE, 0, 0, HINTS)
        val size = matrix.width + 2 * QUIET
        val path =
            buildString {
                for (y in 0 until matrix.height) {
                    var x = 0
                    while (x < matrix.width) {
                        if (matrix[x, y]) {
                            val start = x
                            while (x < matrix.width && matrix[x, y]) x++
                            append("M${start + QUIET},${y + QUIET}h${x - start}v1h-${x - start}z")
                        } else {
                            x++
                        }
                    }
                }
            }
        val dp = size * DP_PER_MODULE
        return """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by GuideQrTest from https://stationbreak.tv/guide/ (see that test); do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${dp}dp"
    android:height="${dp}dp"
    android:viewportWidth="$size"
    android:viewportHeight="$size">
    <path android:fillColor="$CREAM" android:pathData="M0,0h${size}v${size}h-${size}z" />
    <path android:fillColor="$INK" android:pathData="$path" />
</vector>
"""
    }

    private data class Run(
        val x: Int,
        val y: Int,
        val n: Int,
    )

    private fun dark(text: String): List<Run> {
        val data = Regex("""pathData="(M\d+,\d+h\d+v1h-\d+z[^"]*)"""").find(text)!!.groupValues[1]
        return Regex("""M(\d+),(\d+)h(\d+)v1h-\3z""")
            .findAll(data)
            .map { Run(it.groupValues[1].toInt(), it.groupValues[2].toInt(), it.groupValues[3].toInt()) }
            .toList()
    }

    // Rasterises the drawable's own path data (ink runs on cream) at SCALE pixels a module, reads it as a camera would.
    private fun decode(text: String): String {
        val view = Regex("""viewportWidth="(\d+)"""").find(text)!!.groupValues[1].toInt()
        val side = view * SCALE
        val pixels = IntArray(side * side) { CREAM_RGB }
        for ((x, y, n) in dark(text)) {
            for (py in y * SCALE until (y + 1) * SCALE) {
                for (px in x * SCALE until (x + n) * SCALE) pixels[py * side + px] = INK_RGB
            }
        }
        val bitmap = BinaryBitmap(HybridBinarizer(RGBLuminanceSource(side, side, pixels)))
        val hints = mapOf(DecodeHintType.PURE_BARCODE to false)
        return QRCodeReader().decode(bitmap, hints).text
    }

    private companion object {
        val HINTS =
            mapOf(
                EncodeHintType.ERROR_CORRECTION to ErrorCorrectionLevel.M,
                EncodeHintType.MARGIN to 0,
            )
        const val QUIET = 4
        const val DP_PER_MODULE = 6
        const val SCALE = 8
        const val CREAM = "#FFF3EEE3"
        const val INK = "#FF1C1B19"
        const val CREAM_RGB = 0xFFF3EEE3.toInt()
        const val INK_RGB = 0xFF1C1B19.toInt()
    }
}
