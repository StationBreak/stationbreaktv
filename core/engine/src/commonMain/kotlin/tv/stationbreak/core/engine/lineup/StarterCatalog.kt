package tv.stationbreak.core.engine.lineup

import tv.stationbreak.core.model.OrderingMode
import tv.stationbreak.core.rules.Source

/**
 * The themed starter catalog (spec 12): original channel names, each with a one-line personality. A recipe is filled
 * later from whatever the library has, through genre, tag and year-range sources only, with spelling variants listed as
 * separate sources because scrapers disagree. Spread the numbers out inside a band so later recipes can slot in
 * between; a shipped key or number never changes and is never reused.
 */
object StarterCatalog : StarterCatalogView {
    /**
     * The catalog's version. It goes up with any change to what a recipe airs (sources, exclusions, collection hints,
     * ordering), its ceiling or opt-in, or a recipe or leftovers recipe added or removed. The frozen manifests in the
     * tests hold the catalog to that.
     */
    const val VERSION = 1

    override val version: Int = VERSION

    override val recipes: List<Recipe> =
        kidsBand + generalBand + dramaBand + genreBand + worldBand + premiumBand

    /** The leftovers recipes. The kids' one, `kids-odds-and-ends`, always ships with a ceiling and is never retired. */
    override val leftovers: List<LeftoversRecipe> =
        listOf(
            LeftoversRecipe(
                key = "kids-odds-and-ends",
                name = "Kids' Odds & Ends",
                personality = "Whatever the other kids' channels didn't take, still safe to watch.",
                number = 99,
                maxRating = "PG",
            ),
            LeftoversRecipe(
                key = "odds-and-ends",
                name = "Odds & Ends",
                personality = "Whatever the other channels didn't take. Expect surprises.",
                number = 199,
                maxRating = null,
            ),
        )

    override val retiredNumbers: Set<Int> = emptySet()

    override val retiredKeys: Set<String> = emptySet()

    /** The recipe with this key, or null. */
    fun recipe(key: String): Recipe? = recipes.firstOrNull { it.key == key }
}

private fun genres(vararg names: String): List<Source> = names.map { Source.Genre(it) }

private fun tags(vararg names: String): List<Source> = names.map { Source.Tag(it) }

private fun years(
    from: Int,
    to: Int,
): List<Source> = listOf(Source.YearRange(from = from, to = to))

@Suppress("LongParameterList")
private fun recipe(
    band: Band,
    n: Int,
    key: String,
    name: String,
    says: String,
    sources: List<Source>,
    rating: String? = null,
    hints: List<String> = emptyList(),
    order: OrderingMode? = null,
    optIn: Boolean = false,
): Recipe =
    Recipe(
        key = key,
        name = name,
        personality = says,
        band = band,
        number = n,
        optIn = optIn,
        sources = sources,
        exclusions = emptyList(),
        maxRating = rating,
        ordering = order,
        collectionHints = hints,
    )

