package tv.stationbreak.core.engine.audit

/** What a profile library is there to test: the titles (by their invented names) that show it, and what it shows. */
internal class ProfileCase(
    val titles: List<String>,
    val what: String,
)

/** One profile library: a snapshot generated in code from invented titles, and the cases it carries. */
internal class Profile(
    val key: String,
    val description: String,
    val input: AuditInput,
    val cases: List<ProfileCase>,
)

/**
 * The profile libraries (spec: lineup-seats-and-gaps, section 2): a sitcom household, a horror fan, a kids' household,
 * an anime viewer, a broad library of 1,900 titles and a thin server of 200. Each is generated by code, with invented
 * titles, and the audit's output on each is pinned in `core/engine/src/audit/golden`. Nothing in them is, or is meant
 * to resemble, a real person's library.
 */
internal object ProfileLibraries {
    val keys: List<String> =
        listOf("sitcom-household", "horror-fan", "kids-household", "anime-viewer", "broad-1900", "thin-200")

    fun build(key: String): Profile =
        when (key) {
            "sitcom-household" -> SitcomHousehold.build()
            "horror-fan" -> HorrorFan.build()
            "kids-household" -> KidsHousehold.build()
            "anime-viewer" -> AnimeViewer.build()
            "broad-1900" -> BroadLibrary.build(BroadLibrary.TITLES)
            "thin-200" -> BroadLibrary.buildThin()
            else -> throw IllegalArgumentException("Not a profile library: ${key.length} characters")
        }

    fun all(): List<Profile> = keys.map(::build)
}

// The invented stand-ins of the cases, spelled once so a library and its test agree on them.
internal object CaseTitles {
    const val ADULT_ANIMATED_SITCOM = "Brasenfa Quinolma"
    const val SITCOM_WITH_AN_EXTRA_GENRE = "Velmiren Dartorlo"
    val SMALL_HORROR_SHELF = listOf("Kyzupe Lodarxi", "Fabravel Mitorsen", "Quinkyol Renmaxi", "Zupefa Olbralo")
}
